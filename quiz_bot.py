async def handle_callback(update: Update, context: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query
    await query.answer()

    data = query.data
    chat_id = update.effective_chat.id

    if data == "start_quiz":
        user_progress[chat_id] = 0
        await query.message.delete()
        await send_question(update, context, 0)
        return

    if data.startswith("ans_"):
        parts = data.split("_")
        q_index = int(parts[1])
        selected_option = int(parts[2])

        q_data = QUIZ_DATA[q_index]

        if selected_option in q_data["correct"]:
            if q_index == len(QUIZ_DATA) - 1:
                final_text = (
                    "🎉 <b>ПОЗДРАВЛЯЮ! ТЫ ПРОШЛА КВИЗ НА 100%!</b> 🏆\n\n"
                    "Ты идеально знаешь Сашу, все его фишки, вкусы и секретики"
                    " ❤️\nСпасибо за твоё тепло и за то, что ты рядом!"
                )
                await query.message.edit_text(final_text, parse_mode="HTML")
            else:
                next_q = q_index + 1
                user_progress[chat_id] = next_q
                await query.message.delete()
                await send_question(update, context, next_q)
        else:
            error_msg = q_data.get("custom_error")
            if not error_msg:
                error_msg = random.choice(WRONG_ANSWER_TEASES)

            await query.message.reply_text(f"❌ {error_msg}")


async def photo_handler(update: Update, context: ContextTypes.DEFAULT_TYPE):
    photo = update.message.photo[-1]
    file_id = photo.file_id
    await update.message.reply_text(
        f"📸 <b>file_id этой фотки:</b>\n<code>{file_id}</code>",
        parse_mode="HTML",
    )


